def names_join(keys):
    """多個策略合併成一句話（創高拉回、噴出後整理都叫「強勢續攻」，只列一次）"""
    out = []
    for k in keys:
        n = GROUP_NAMES.get(k, STRATEGY_NAMES[k])
        if n not in out:
            out.append(n)
    return "、".join(out)

